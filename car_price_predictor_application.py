import streamlit as st
import pandas as pd
import numpy as np
import joblib

#Load the pickle files
bundle = joblib.load('used_car_price_model.pkl')
model = bundle['model']
label_encoders = bundle['label_encoders']
scaler = bundle['scaler']
feature_columns = bundle['feature_columns']
brand_values = bundle['brand_values']
model_values = bundle['model_values']
variant_values = bundle['variant_values']
lookup_df = pd.read_pickle("vehicle_lookup.pkl")

# Page Configuration
st.set_page_config(page_title='Used Car Price Predictor', page_icon='🚗', layout='centered')
st.title("🚘 Used Car Price Predictor")
st.markdown("Estimate the market price of a used vehicle based on its brand, model, variant and usage information.")

# Get the input from user in two columns
col1, col2 = st.columns(2)

with col1:
    brand = st.selectbox("Brand", sorted(brand_values), index=None, placeholder="Choose a brand")
    
    available_models = sorted(lookup_df[lookup_df["brand"] == brand]["model"].unique())
    model_name = st.selectbox("Model", available_models)
    
    available_variants = sorted(lookup_df[(lookup_df["brand"] == brand) & (lookup_df["model"] == model_name)]["variant"].unique())
    variant = st.selectbox("Variant", available_variants)

    fuel_type = st.selectbox("Fuel Type", ["PETROL", "DIESEL", "CNG", "LPG", "HYBRID", "ELECTRIC"])

with col2:
    transmission = st.radio("Transmission Type", ["MANUAL", "AUTOMATIC"], horizontal=True)  
    make_year = st.slider("Make Year", 1995, 2026, 2015)  
    km_driven = st.slider("Kilometers Driven", 0, 500000, 30000, step=1000)
    previous_owners = st.slider("No. of Previous Owners", 1, 10, 1)

# Predict Button Action
if st.button("Predict Price"):
    vehicle_row = lookup_df[(lookup_df["brand"]==brand) & (lookup_df["model"]==model_name) & (lookup_df["variant"]==variant)]

    if vehicle_row.empty:
        st.error("Vehicle specifications not found.")
    else:
        vehicle_row = vehicle_row.iloc[0]
        
        # Create empty record
        input_df = pd.DataFrame(np.zeros((1, len(feature_columns))), columns=feature_columns)

        # Label Encoding
        input_df["brand"] = label_encoders["brand"].transform([brand])[0]
        input_df["model"] = label_encoders["model"].transform([model_name])[0]
        input_df["variant"] = label_encoders["variant"].transform([variant])[0]

        numerical_cols = ['make_year', 'km_driven', 'length', 'width', 'wheel_base', 'kerb_weight', 'max_power_delivered', 'max_torque_delivered', 'engine_capacity_cc', 'previous_owners']

        numerical_values = pd.DataFrame([[make_year, km_driven, vehicle_row["length"], vehicle_row["width"], vehicle_row["wheel_base"], vehicle_row["kerb_weight"], vehicle_row["max_power_delivered"], vehicle_row["max_torque_delivered"], vehicle_row["engine_capacity_cc"], previous_owners]], columns=numerical_cols)

        input_df[numerical_cols] = scaler.transform(numerical_values)

        # One Hot Encoding
        body_col = f'body_type_{vehicle_row["body_type"]}'
        gear_col = f'gear_box_{vehicle_row["gear_box"]}'
        drive_col = f'drive_type_{vehicle_row["drive_type"]}'
        steering_col = f'steering_type_{vehicle_row["steering_type"]}'
        fuel_col = f'fuel_type_{fuel_type}'
        brake_col = f'rear_brake_type_{vehicle_row["rear_brake_type"]}'
        transmission_col = f'transmission_{transmission}'

        categorical_cols = [body_col, gear_col, drive_col, steering_col, fuel_col, brake_col, transmission_col]
        for col in categorical_cols:
            if col in input_df.columns:
                input_df[col] = 1

        # Make the prediction
        prediction = model.predict(input_df)[0]
        prediction = max(prediction, 0)
        lower_price = prediction * 0.90
        upper_price = prediction * 1.10

        # Display the results
        st.success(f"Estimated Price: ₹ {prediction:,.0f}")
        st.info(f"Expected Market Range: ₹ {lower_price:,.0f} - ₹ {upper_price:,.0f}")
        st.metric("Predicted Price (Lakhs)", f"{prediction/100000:.2f} L")
        
st.markdown("---")
 
st.caption(
"""
⚠️ Disclaimer: The estimated price is generated by an AI-based machine learning model and is intended for informational purposes only. Actual market prices may vary, and the prediction should not be relied upon as the sole basis for real-world pricing or purchasing decisions.
"""
)





